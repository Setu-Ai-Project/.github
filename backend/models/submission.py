from datetime import datetime, timezone
from typing import Optional
from sqlalchemy import Column, JSON
from sqlmodel import Field, SQLModel


class SubmissionStatus:
    """The only three allowed status words. Use these instead of typing strings."""
    PENDING = "pending"
    PASSED = "passed"
    NEEDS_REVISION = "needs_revision"


class SubmissionBase(SQLModel):
    # Foreign key pointing to the user who made the submission
    user_id: int = Field(foreign_key="users.id", index=True, nullable=False)
    # Foreign key pointing to the challenge being submitted for
    challenge_id: int = Field(foreign_key="challenges.id", index=True, nullable=False)
    # The learner's submitted answer text
    answer_text: str
    # Current status of the submission (pending, passed, or needs_revision)
    status: str = Field(default=SubmissionStatus.PENDING, nullable=False)
    # Amount of XP awarded for this submission attempt
    xp_awarded: int = Field(default=0, ge=0)
    # Number of this attempt for the challenge (starts at 1)
    attempt_number: int = Field(default=1, ge=1)
    # Timestamp when the submission was created in UTC
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc), nullable=False)


class Submission(SubmissionBase, table=True):
    __tablename__ = "submissions"

    # Primary key identifier for the submission record
    id: Optional[int] = Field(default=None, primary_key=True)
    # List of feedback strings generated by the verification checker
    feedback: list[str] = Field(default_factory=list, sa_column=Column(JSON))


class SubmissionRead(SubmissionBase):
    id: int
    feedback: list[str] = []
